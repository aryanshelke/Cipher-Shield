"""Layer 3: Canary Token Downstream Output Protection.

Generates high-entropy, session-specific canary tokens embedded into LLM system prompts.
Scans all outgoing LLM completions and intercepts responses if the canary token leaks,
preventing system prompt exfiltration and data poisoning.
"""

from __future__ import annotations

import logging
import secrets
from typing import Optional

from fastapi import HTTPException, status

logger = logging.getLogger("canary_layer")


def generate_canary_token(num_bytes: int = 8) -> str:
    """Generate a unique, cryptographically secure high-entropy canary token.
    
    Args:
        num_bytes: Number of random bytes (default 8 bytes = 16 hex characters).
        
    Returns:
        Formatted canary token string, e.g. '[CANARY_TOKEN: 4a2b9f10c8e317d5]'.
    """
    token_hex = secrets.token_hex(num_bytes)
    return f"[CANARY_TOKEN: {token_hex}]"


def sanitize_output(llm_response: str, canary_token: str) -> str:
    """Scan outgoing LLM completion for canary token leakage.
    
    If the canary token is detected in the response text, the response is
    immediately dropped and an HTTP 403 Forbidden exception is raised.
    
    Args:
        llm_response: Text generated by downstream LLM.
        canary_token: The session-specific canary token embedded in the system prompt.
        
    Returns:
        The sanitized response text if clean.
        
    Raises:
        HTTPException (403): If the canary token is detected in the outgoing text.
    """
    if not llm_response or not canary_token:
        return llm_response

    # Check for direct inclusion or unescaped token hex
    raw_hex = canary_token.replace("[CANARY_TOKEN: ", "").replace("]", "").strip()
    
    if canary_token in llm_response or (raw_hex and raw_hex in llm_response):
        logger.warning(
            f"[LAYER 3 INTERCEPTED] System Prompt Leak Detected! Canary token '{canary_token}' "
            "found in outgoing LLM completion. Dropping response."
        )
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="System Prompt Leak Detected: Blocked by Layer 3 Canary Token",
        )

    return llm_response

